        <h2>3. Дозволи пристрою</h2>
        <p>Застосунок може запитувати доступ до геопозиції, сповіщень, камери, фотографій або файлів. Доступ використовується лише для функції, яку обрав користувач, і може бути відкликаний у налаштуваннях Android або iOS.</p>

        <h2>4. Навіщо використовуються дані</h2>
        <p>Дані потрібні для входу й захисту облікового запису, виконання службових завдань у CRM, синхронізації з сервером, надсилання робочих сповіщень, показу погоди, підтримки користувачів, запобігання зловживанням та аудиту безпеки.</p>

        <h2>5. Кому можуть передаватися дані</h2>
        <p>Ми не продаємо персональні дані й не використовуємо їх для реклами. Для роботи окремих функцій застосовуються постачальники інфраструктури: Google Firebase для доставлення push-сповіщень, Open-Meteo для отримання погоди та постачальник хостингу для роботи серверів ОМЦ. Дані передаються лише в обсязі, необхідному для відповідної функції.</p>

        <h2>6. Зберігання та захист</h2>
        <p>Передавання даних відбувається через захищене HTTPS-з’єднання. Токен входу зберігається в захищеному сховищі пристрою. Доступ до серверних даних обмежено ролями працівників. Дані зберігаються стільки, скільки це потрібно для роботи Центру, виконання законних обов’язків і захисту системи.</p>

        <h2>7. Видалення та виправлення даних</h2>
        <p>Оскільки облікові записи створює організація для службового використання, користувач може звернутися до адміністратора ОМЦ для виправлення або видалення своїх даних та облікового запису. Після виходу із застосунку локальний токен входу видаляється, а push-токен пристрою відкликається.</p>

